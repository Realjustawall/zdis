import { test, expect } from './test-fixtures';

test('Persian UI preserves names/messages, localizes validation, and keeps navigation available', async ({ page, context }, info) => {
  test.skip(info.project.name !== 'mobile-chromium', 'Phone localization regression');
  await page.addInitScript(() => { if(!localStorage.getItem('zdis.locale'))localStorage.setItem('zdis.locale','fa');if(!localStorage.getItem('ZDIS.theme'))localStorage.setItem('ZDIS.theme','dark'); });
  const response = await context.request.post('/api/auth/login',{data:{identifier:'admin',password:'cNL2*8o$1F;"'}});
  const auth = await response.json(), headers={'x-csrf-token':auth.csrfToken};
  const suffix=Date.now().toString(36);
  const created=await context.request.post('/api/admin/users',{headers,data:{username:'lang'+suffix,email:'lang'+suffix+'@example.com',displayName:'Download',password:'Language-Name#2026',role:'member',mustChangePassword:false}});
  expect(created.status()).toBe(201);
  const createdGroup=await context.request.post('/api/groups',{headers,data:{name:'Settings'}});
  expect(createdGroup.status()).toBe(201);
  await page.goto('/');
  await expect(page.locator('html')).toHaveAttribute('dir','rtl');
  await page.locator('.home-friends-link').click();
  await expect(page.locator('.mobile-dock')).toBeVisible();
  await page.getByRole('button',{name:'پیام‌ها',exact:true}).click();
  await page.locator('.sidebar .nav-item').filter({hasText:'فهرست اعضا'}).click();
  await expect(page.getByText('Download',{exact:true})).toBeVisible();
  await expect(page.locator('.mobile-dock')).toBeVisible();
  await page.getByRole('button',{name:'پیام‌ها',exact:true}).click();
  await page.locator('.mobile-server-rail').getByTitle('Settings',{exact:true}).click();
  await expect(page.locator('.group-header-copy strong')).toHaveText('Settings');
  await page.locator('.channel-nav-row').filter({hasText:'general'}).locator('button').first().click();
  const send=page.locator('.composer-btn.send');
  await expect(send).toBeDisabled();
  await expect(send).toHaveCSS('background-color','rgb(100, 116, 139)');
  await page.locator('.composer textarea').fill('Save Changes');
  await expect(send).toBeEnabled();
  await expect(send).toHaveCSS('background-color','rgb(37, 99, 235)');
  await page.locator('.composer textarea').press('Enter');
  await expect(page.locator('.message .content').getByText('Save Changes',{exact:true})).toBeVisible();
  await page.locator('.main-head').getByTitle('بازگشت',{exact:true}).click();
  await page.locator('.mobile-server-rail').getByTitle('مدیریت',{exact:true}).click();
  await expect(page.locator('.admin.admin-fa')).toHaveAttribute('dir','rtl');
  await page.locator('.admin-nav').getByRole('button',{name:'کاربران',exact:true}).click();
  await page.getByRole('button',{name:/ساخت حساب جدید/}).click();
  await page.getByLabel('نام نمایشی').fill('کاربر آزمایشی');
  await page.getByLabel('نام کاربری').fill('weak'+suffix);
  await page.getByLabel('ایمیل').fill('weak'+suffix+'@example.com');
  await page.getByLabel('رمز عبور موقت').fill('weak');
  await page.getByRole('button',{name:'ساخت حساب',exact:true}).click();
  await expect(page.getByText('رمز عبور باید حداقل ۱۰ نویسه داشته باشد.',{exact:true})).toBeVisible();
  await expect(page.getByText('رمز عبور باید شامل عدد باشد.',{exact:true})).toBeVisible();
  await page.locator('.modal-head .close').last().click();
  await page.locator('.admin-mobile-back').click();
  await page.getByRole('button',{name:'بازگشت به گفتگو',exact:true}).click();
  await page.getByRole('button',{name:'حساب کاربری',exact:true}).click();
  await page.getByRole('group',{name:'تغییر زبان',exact:true}).getByRole('button',{name:'English',exact:true}).click();
  await expect(page.locator('html')).toHaveAttribute('lang','en');
  await expect(page.getByText('Direct messages',{exact:true})).toBeVisible();
  await page.locator('.mobile-server-rail').getByTitle('Administration',{exact:true}).click();
  await expect(page.locator('.admin.admin-fa')).toHaveAttribute('dir','ltr');
});
